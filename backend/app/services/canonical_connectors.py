def resolve_canonical_key(raw_key: str) -> str:
    """Résout une clé brute ou un alias vers la clé canonique parmi les 22."""
    clean = raw_key.strip().lower()
    if clean in CANONICAL_INDEX:
        return clean
    if clean in CONNECTOR_KEY_ALIASES:
        return CONNECTOR_KEY_ALIASES[clean]
    hyphen_or_underscore = clean.replace("-", "_")
    if hyphen_or_underscore in CANONICAL_INDEX:
        return hyphen_or_underscore
    return clean


def get_canonical_connector(key: str) -> dict[str, Any] | None:
    canonical = resolve_canonical_key(key)
    return CANONICAL_INDEX.get(canonical)
