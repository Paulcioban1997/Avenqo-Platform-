import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const localeSource = readFileSync(resolve(root, "src/lib/i18n/locales.ts"), "utf8");
const localeEntries = localeSource.split("export const LOCALES:")[1].split("];", 1)[0];
const locales = [...localeEntries.matchAll(/code:\s*"([^"]+)"/g)].map((match) => match[1]);
const sections = ["auth", "company", "dashboardHome", "assistant", "admin"];
const catalogs = {};

for (const locale of locales) {
  const source = JSON.parse(
    readFileSync(resolve(root, `../frontend/assets/i18n/${locale}.json`), "utf8"),
  );
  catalogs[locale] = Object.fromEntries(sections.map((section) => [section, source[section]]));
}

writeFileSync(
  resolve(root, "src/lib/i18n/application-catalogs.generated.json"),
  `${JSON.stringify(catalogs)}\n`,
  "utf8",
);

const output = `/* Generated by scripts/generate-app-catalogs.mjs. Do not edit manually. */
import type { LocaleCode } from "./types";
import catalogs from "./application-catalogs.generated.json";

export type ApplicationCatalog = (typeof catalogs)["en"];
export const APPLICATION_CATALOGS: Record<LocaleCode, ApplicationCatalog> = catalogs;

export function getApplicationCatalog(locale: LocaleCode | string): ApplicationCatalog {
  return APPLICATION_CATALOGS[locale as LocaleCode] ?? APPLICATION_CATALOGS.en;
}
`;

writeFileSync(resolve(root, "src/lib/i18n/generated-app-catalogs.ts"), output, "utf8");
console.log(`Generated ${locales.length} compact application catalogs.`);