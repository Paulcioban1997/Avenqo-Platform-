import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const locales = JSON.parse(
  readFileSync(resolve(root, "../shared/locales/canonical_locales.json"), "utf8"),
).map((locale) => locale.code);
const sections = ["auth", "company", "dashboardHome", "assistant", "admin", "phase4e"];
const catalogs = {};
const voiceAuthMessages = JSON.parse(
  readFileSync(resolve(root, "../shared/locales/voice_auth_messages.json"), "utf8"),
);

for (const locale of locales) {
  const source = JSON.parse(
    readFileSync(resolve(root, `../frontend/assets/i18n/${locale}.json`), "utf8"),
  );
  catalogs[locale] = Object.fromEntries(sections.map((section) => [section, source[section]]));
}

writeFileSync(
  resolve(root, "src/lib/i18n/application-catalogs.generated.json"),
  `${JSON.stringify(catalogs)}\n`,
  "utf8",
);

const output = `/* Generated by scripts/generate-app-catalogs.mjs. Do not edit manually. */
import type { LocaleCode } from "./types";
import catalogs from "./application-catalogs.generated.json";

export type ApplicationCatalog = (typeof catalogs)["en"];
export const APPLICATION_CATALOGS: Record<LocaleCode, ApplicationCatalog> = catalogs;

export function getApplicationCatalog(locale: LocaleCode | string): ApplicationCatalog {
  return APPLICATION_CATALOGS[locale as LocaleCode] ?? APPLICATION_CATALOGS.en;
}
`;

writeFileSync(resolve(root, "src/lib/i18n/generated-app-catalogs.ts"), output, "utf8");
writeFileSync(
  resolve(root, "src/lib/i18n/voice-auth-messages.generated.ts"),
  `/* Generated by scripts/generate-app-catalogs.mjs. Do not edit manually. */\nimport type { LocaleCode } from "./types";\nimport messages from "./voice-auth-messages.generated.json";\n\nexport const VOICE_AUTH_MESSAGES: Record<LocaleCode, readonly string[]> = messages;\n`,
  "utf8",
);
writeFileSync(
  resolve(root, "src/lib/i18n/voice-auth-messages.generated.json"),
  `${JSON.stringify(voiceAuthMessages)}\n`,
  "utf8",
);
console.log(`Generated ${locales.length} compact application catalogs.`);